// CAD estimate/manual/unknown sources against a disposable native acceptance fixture.
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
const directory=process.argv[2];
const {chromium}=await import(process.env.FORGEPDM_PLAYWRIGHT||"/tmp/forgepdm-material-web-qa/node_modules/playwright-core/index.mjs");
const config=JSON.parse(await fs.readFile(path.join(directory,"connection.json"),"utf8"));
const native=JSON.parse(await fs.readFile(path.join(directory,"mass-fallback-freecad-report.json"),"utf8"));
const browser=await chromium.launch({executablePath:"/usr/bin/google-chrome",headless:true,args:["--no-sandbox","--disable-dev-shm-usage"]});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
const pageErrors=[],checks=[];page.on("pageerror",e=>pageErrors.push(e.message));
try{
 await page.goto(config.url+"/app/");
 await page.locator("#username").fill("web-admin");await page.locator("#password").fill(config.password);
 const login=page.waitForResponse(r=>r.url().endsWith("/auth/login")&&r.status()===200);
 await page.locator("#login-button").click();const token=(await(await login).json()).access_token;
 const call=async(method,url,data)=>{const r=await page.request.fetch(config.url+"/api/v1"+url,{method,headers:{Authorization:`Bearer ${token}`},data});assert.ok(r.ok(),await r.text());return r.json();};
 const open=async item=>{await page.evaluate(item=>{location.hash=new URLSearchParams({item:item.id,revision:item.current_revision_id}).toString();},item);await page.waitForFunction(n=>document.querySelector(".detail-title-line h2")?.textContent===n,item.number);await page.getByRole("tab",{name:"Description",exact:true}).click();await page.getByRole("heading",{name:"Standard part mass",exact:true}).waitFor();};
 await open(native.items.estimate);
 await page.getByText("Estimated from CAD",{exact:true}).waitFor();
 assert.match(await page.locator("#tab-content").innerText(),/7800 kg\/m³.*simplified threads/);
 checks.push("CAD estimates show their source, reference density and simplified-thread limitation");
 await page.getByText("Enter mass manually",{exact:true}).click();
 await page.getByLabel("Mass per piece (g)",{exact:true}).fill("11.75");await page.getByLabel("Mass note (optional)").fill("Measured sample");
 const saved=page.waitForResponse(r=>r.request().method()==="PUT"&&r.url().endsWith("/reference-mass/fallback"));
 await page.getByRole("button",{name:"Save manual mass",exact:true}).click();assert.equal((await saved).status(),200);
 await page.getByText("Manual entry",{exact:true}).waitFor();await page.getByText("11.75 g per piece",{exact:true}).waitFor();
 checks.push("manual grams entry explicitly replaces an estimate and displays its note");
 const revision=native.items.estimate.current_revision_id;
 const previous=await call("GET",`/revisions/${revision}/reference-mass`);
 await call("PUT",`/revisions/${revision}/reference-mass/fallback`,{method:"manual",mass_g:"13.5",note:"Concurrent update",expected_token:previous.token});
 await page.getByText("Enter mass manually",{exact:true}).click();await page.getByLabel("Mass per piece (g)",{exact:true}).fill("12");
 await page.getByRole("button",{name:"Save manual mass",exact:true}).click();
 await page.getByRole("alert").filter({hasText:"Mass changed"}).waitFor();
 assert.equal((await call("GET",`/revisions/${revision}/reference-mass`)).mass_kg,"0.0135");
 checks.push("stale manual edits are rejected without overwriting a concurrent value");
 await open(native.items.unknown);
 assert.match(await page.locator("#tab-content").innerText(),/Mass unavailable/);
 assert.doesNotMatch(await page.locator("#tab-content").innerText(),/0 g per piece/);
 checks.push("unknown mass is displayed as unavailable rather than zero");
 await page.getByText("Enter mass manually",{exact:true}).click();await page.getByLabel("Mass per piece (g)",{exact:true}).fill("8.25");
 await page.getByRole("button",{name:"Save manual mass",exact:true}).click();await page.getByText("8.25 g per piece",{exact:true}).waitFor();
 checks.push("unknown-material entries accept explicit manual mass without density");
 await open(native.items.manual);
 await page.getByText("12.5 g per piece",{exact:true}).waitFor();assert.equal(await page.getByRole("button",{name:"Save manual mass",exact:true}).count(),0);
 checks.push("Released manual mass remains read-only");
 const supplierSpec={geometry:{Type:"ISO4762",Diameter:"M8",Length:"30"},material:"steel",grade:"10.9",finish:"plain"};
 const cell=JSON.stringify(supplierSpec).replaceAll('"','""');
 const csv=`specification_json,supplier,source_article,source_url,mass,unit,quantity\n"${cell}",QA supplier,QA-16,https://example.com/QA-16,16,g,1\n`;
 await call("POST","/reference-masses/import",{csv_text:csv});
 const supplier=await call("POST","/items",{kind:"part",number_series:"S",name:"Supplier priority check",standard_specification:supplierSpec});
 await open(supplier);await page.getByText("Supplier reference",{exact:true}).waitFor();await page.getByRole("link",{name:"Supplier source"}).waitFor();
 assert.equal(await page.getByText("Enter mass manually",{exact:true}).count(),0);
 checks.push("verified supplier references retain their source display and cannot be overwritten by fallback controls");
 await page.setViewportSize({width:390,height:844});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 checks.push("fallback mass view fits mobile viewport");
 assert.deepEqual(pageErrors,[]);await page.screenshot({path:path.join(directory,"mass-fallback-mobile.png"),fullPage:true});
 await fs.writeFile(path.join(directory,"mass-fallback-browser-report.json"),JSON.stringify({checks,pageErrors},null,2));console.log(JSON.stringify({checks,pageErrors}));
}finally{await browser.close();}
