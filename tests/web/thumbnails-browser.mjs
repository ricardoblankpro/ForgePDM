// Real Chrome against a disposable fixture populated by native CAD commands.
import assert from "node:assert/strict";
import {readFile, writeFile} from "node:fs/promises";
import {pathToFileURL} from "node:url";
import path from "node:path";
const directory=process.argv[2];
const config=JSON.parse(await readFile(path.join(directory,"connection.json"),"utf8"));
const {chromium}=await import(pathToFileURL(process.env.FORGEPDM_PLAYWRIGHT || "/tmp/forgepdm-thumbnails-browser/node_modules/playwright-core/index.mjs"));
const browser=await chromium.launch({executablePath:process.env.FORGEPDM_BROWSER || "/usr/bin/google-chrome",headless:true,args:["--no-sandbox","--disable-dev-shm-usage"]});
const context=await browser.newContext({viewport:{width:1280,height:1000}}), page=await context.newPage();
const report={checks:[],pageErrors:[],csp:[]};
const check=(label,value=true)=>{assert.ok(value,label);report.checks.push(label);};
page.on("pageerror",error=>report.pageErrors.push(error.message));
await page.addInitScript(()=>{window.thumbnailCSP=[];document.addEventListener("securitypolicyviolation",event=>window.thumbnailCSP.push(event.violatedDirective));});
try {
  await page.goto(config.base_url+"/app/");
  await page.locator("#username").fill(config.username);await page.locator("#password").fill(config.password);
  const login=page.waitForResponse(r=>r.url().endsWith("/auth/login")&&r.status()===200);
  await page.locator("#login-button").click();
  const token=(await (await login).json()).access_token;
  await page.locator(".item-row").first().waitFor();
  const headers={Authorization:`Bearer ${token}`};
  const catalog=await fetch(config.base_url+"/api/v1/catalog/items?limit=100",{headers});
  let items;
  if(catalog.ok) items=(await catalog.json()).items;
  else items=(await (await fetch(config.base_url+"/api/v1/items?limit=100",{headers})).json()).items;
  const item=items.find(i=>i.kind==="part");assert.ok(item);
  await page.evaluate(id=>location.hash=new URLSearchParams({item:id}).toString(),item.id);
  const picker=page.getByRole("combobox",{name:"CAD snapshot for preview"});
  await picker.waitFor();
  await page.waitForFunction(()=>document.querySelector(".thumbnail-image img")?.naturalWidth===384);
  check("overview displays an authorized 384px native isometric image");
  check("snapshot selector exposes historical uploads",await picker.locator("option").count()>1);
  const latest=await page.locator(".thumbnail-image img").getAttribute("src");
  await picker.selectOption("1");
  await page.waitForFunction(previous=>{const i=document.querySelector(".thumbnail-image img");return i?.naturalWidth===384&&i.src!==previous;},latest);
  check("selecting an older upload replaces the preview without changing revision");
  await page.screenshot({path:path.join(directory,"web-thumbnail.png"),fullPage:true});
  await page.getByRole("tab",{name:"Files & datasets",exact:true}).click();
  await page.waitForFunction(()=>document.querySelector(".thumbnail-image img")?.naturalWidth===384);
  check("files tab displays the same selected-revision preview controls");
  await page.route("**/api/v1/files/*/thumbnail",route=>route.fulfill({status:404,contentType:"application/json",body:'{"detail":"missing"}'}));
  await page.getByRole("combobox",{name:"CAD snapshot for preview"}).selectOption("1");
  await page.getByText("No preview available",{exact:true}).waitFor();
  check("a missing preview preserves file downloads",await page.getByRole("button",{name:/Download /}).count()>0);
  await page.unroute("**/api/v1/files/*/thumbnail");
  let release;
  const delayed=new Promise(resolve=>release=resolve);
  await page.route("**/api/v1/files/*/thumbnail",async route=>{await delayed;await route.continue();});
  await page.getByRole("combobox",{name:"CAD snapshot for preview"}).selectOption("0");
  await page.getByRole("tab",{name:"Where used",exact:true}).click();
  release();
  await page.waitForTimeout(150);
  check("a delayed preview cannot reappear in another tab",await page.locator(".thumbnail-image img").count()===0);
  await page.unroute("**/api/v1/files/*/thumbnail");
  await page.getByRole("tab",{name:"Overview",exact:true}).click();
  await page.waitForFunction(()=>document.querySelector(".thumbnail-image img")?.naturalWidth===384);
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(100);
  check("preview reflows without horizontal page overflow",await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.locator("#logout").click();
  check("logout removes preview and source URLs",await page.locator(".thumbnail-image img").count()===0);
  report.csp=await page.evaluate(()=>window.thumbnailCSP);
  check("no browser errors",report.pageErrors.length===0);
  check("authorized blob images pass CSP",report.csp.length===0);
  report.status="passed";
} catch(error) {report.status="failed";report.error=String(error);throw error;}
finally {await writeFile(path.join(directory,"web-report.json"),JSON.stringify(report,null,2));await browser.close();}
