// Isolated served fixture only; no production engineering records are accessed.
import assert from "node:assert/strict";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {pathToFileURL} from "node:url";
const directory = process.argv[2];
const config = JSON.parse(await readFile(path.join(directory,"connection.json"),"utf8"));
const {chromium} = await import(pathToFileURL(process.env.FORGEPDM_PLAYWRIGHT || "/tmp/forgepdm-web-qa/node_modules/playwright-core/index.mjs"));
const browser = await chromium.launch({executablePath:process.env.FORGEPDM_BROWSER || "/usr/bin/google-chrome",headless:true,args:["--no-sandbox","--disable-dev-shm-usage"]});
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const page = await context.newPage();
const report = {scope:"Real Chrome, disposable backend; read-only report/view navigation",checks:[],pageErrors:[],writes:[]};
let reportRequests=0;
page.on("pageerror",e=>report.pageErrors.push(e.message));
page.on("request",r=>{
  if(r.url().endsWith("/bom-report"))reportRequests++;
  if(!["GET","HEAD"].includes(r.method())&&!r.url().endsWith("/auth/login"))report.writes.push(r.method());
});
const check=(name,value=true)=>{assert.ok(value,name);report.checks.push(name);};
try {
  await page.goto(config.url+"/app/");
  await page.locator("#username").fill(config.username);
  await page.locator("#password").fill(config.password);
  await page.locator("#login-button").click();
  await page.locator("#workspace").waitFor({state:"visible"});
  await page.evaluate(root=>{location.hash=new URLSearchParams({item:root.id,revision:root.revision}).toString();},config.root);
  await page.locator(".detail-title-line h2").filter({hasText:config.root.number}).waitFor();
  await page.getByRole("tab",{name:"Bill of materials",exact:true}).click();
  await page.locator(".bom-table tbody tr").nth(2).waitFor();
  const cells=()=>page.locator(".bom-table tbody tr").allTextContents();
  const nested=page.locator(".bom-table tbody tr").nth(1).locator("td");
  check("indented quantities distinguish four per parent from twelve per root",await nested.nth(3).innerText()==="4"&&await nested.nth(4).innerText()==="12");
  check("nested positions retain stored path",await nested.nth(0).innerText()==="1.1");
  check("unknown mass stays unavailable with known subtotal",(await page.locator(".bom-mass").innerText()).includes("Total unavailable. Known subtotal: 0 kg"));
  const initialRequests=reportRequests;
  await page.getByRole("button",{name:"Flattened",exact:true}).click();
  check("flattened combines repeated exact revision to fourteen parts",await page.locator(".bom-table tbody tr").count()===1&&await page.locator(".bom-table tbody td").nth(4).innerText()==="14");
  check("flattened quantity per parent is explicitly unavailable",await page.locator(".bom-table tbody td").nth(3).innerText()==="—");
  await page.getByRole("button",{name:"Direct",exact:true}).click();
  check("direct keeps subassembly and direct part rows",await page.locator(".bom-table tbody tr").count()===2);
  await page.getByRole("button",{name:"Indented",exact:true}).click();
  await page.getByRole("button",{name:"Collapse all",exact:true}).click();
  check("indented collapse retains root lines",await page.locator(".bom-table tbody tr").count()===2);
  await page.getByRole("button",{name:"Expand all",exact:true}).click();
  check("expansion restores server quantities",await page.locator(".bom-table tbody tr").count()===3&&(await cells()).some(v=>v.includes("12")));
  check("view switches use one common fetched snapshot",reportRequests===initialRequests);
  await page.getByRole("button",{name:"Refresh BOM",exact:true}).click();
  await page.locator(".bom-table tbody tr").nth(2).waitFor();
  check("explicit refresh fetches another report",reportRequests===initialRequests+1);
  await page.getByRole("button",{name:"Flattened",exact:true}).click();
  await page.locator(".bom-table").getByRole("button",{name:config.part.number,exact:true}).click();
  await page.waitForFunction(r=>document.querySelector("#revision-picker")?.value===r,config.part.revision);
  check("flattened navigation opens pinned A rather than latest B",(await page.locator(".revision-note").innerText()).includes("Current revision B"));
  check("viewing causes no engineering writes",report.writes.length===0);
  check("no browser exceptions",report.pageErrors.length===0);
  report.status="passed";
  await writeFile(path.join(directory,"bom-reports-browser-report.json"),JSON.stringify(report,null,2)+"\n");
  console.log(`Shared BOM browser QA passed: ${report.checks.length} checks.`);
} finally {await browser.close();}
